import test from "node:test";
import assert from "node:assert/strict";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { FirstSteps, sampleWorkout } from "../app/views/first-steps";
import { blankStartState, starterPlanState } from "../app/views/starter-plan";
import { defaultState } from "../app/domain/training-types";
import { parseFitlog } from "../app/interchange/fitlog";

test("a new log offers a starter plan or a blank log, and the example workout is unchanged", () => {
  const state = defaultState();
  const today = renderToStaticMarkup(createElement(FirstSteps, { state, view: "today", onStarter: () => {}, onBlank: () => {} }));
  assert.match(today, /Welcome to Coach Loop/);
  assert.match(today, /Explore demo/);
  assert.match(today, /See a sample workout/);
  assert.match(today, /Set up my log/);
  assert.match(today, /Use example goals/);
  assert.match(today, /Start blank/);
  assert.match(today, /does not create a workout/);
  assert.match(today, /Restore backup/);
  assert.match(today, /Nothing is logged/);
  assert.match(today, /no AI inside the app/);
  assert.doesNotMatch(today, /Start with an example/);
  assert.doesNotMatch(today, /Change 30 minutes/);
  assert.doesNotMatch(today, /Paste a workout/);
  assert.doesNotMatch(today, /How this works/);
  const started = starterPlanState(state);
  assert.deepEqual(started.goals, ["Bench press 225 lb", "Run a 5k under 30 minutes"]);
  assert.match(started.coachProfile, /one next session/);
  assert.doesNotMatch(started.coachProfile, /Coach profile field/);
  assert.equal(started.workouts.length, 1);
  assert.equal(started.workouts[0]?.name, "Starter session");
  assert.equal(started.workouts[0]?.starterSeed, true);
  assert.equal(started.workouts[0]?.status, "planned");
  assert.deepEqual(started.settings.quickLogActivities, ["run", "bike", "circuit", "yoga"]);
  assert.equal(renderToStaticMarkup(createElement(FirstSteps, { state: started, view: "today", onStarter: () => {}, onBlank: () => {} })), "");
  const blank = blankStartState(state);
  assert.deepEqual(blank.goals, []);
  assert.equal(blank.coachProfile, "");
  assert.deepEqual(blank.settings.quickLogActivities, ["run", "bike", "circuit", "yoga"]);
  assert.equal(renderToStaticMarkup(createElement(FirstSteps, { state: blank, view: "today", onStarter: () => {}, onBlank: () => {} })), "");
  const history = renderToStaticMarkup(createElement(FirstSteps, { state, view: "history", onStarter: () => {}, onBlank: () => {} }));
  assert.match(history, /Choose how to start on Today/);
  const sample = parseFitlog(sampleWorkout(), "lb", {});
  assert.equal(sample.cardio[0]?.name, "Easy bike");
  assert.equal(sample.cardio[0]?.activityType, "bike");
  assert.equal(sample.cardio[0]?.plannedDurationMin, 5);
  assert.deepEqual(sample.exercises.map(exercise => exercise.name), ["Barbell Bench Press", "Pull-up", "Dip", "Dumbbell Lateral Raise"]);
  assert.equal(sample.exercises[0]?.sets[0]?.warmup, true);
  assert.deepEqual(sample.exercises[0]?.sets.slice(1).map(set => set.plannedWeight), [135, 155, 175, 185]);
  assert.equal(sample.exercises[0]?.sets[1]?.plannedWeight, 135);
  assert.equal(sample.exercises[1]?.sets[0]?.loadType, "bodyweight");
  assert.equal(sample.exercises[3]?.sets[0]?.weightMode, "per_hand");
  assert.equal(sample.cardio[1]?.activityType, "mobility");
  assert.equal(sample.cardio[1]?.mobilityMoves.length, 2);
  assert.ok(sample.exercises.every(exercise => exercise.sets.every(set => !set.completed)));
  assert.equal(sample.importWarnings?.length ?? 0, 0);
  assert.equal(state.workouts.length, 0);
  state.workouts.push({ ...sample, status: "completed" });
  assert.equal(renderToStaticMarkup(createElement(FirstSteps, { state, view: "today", onSetup: () => {}, onCoach: () => {}, onSample: () => {} })), "");
  for (const view of ["history", "coach", "progress", "settings"] as const) {
    assert.equal(renderToStaticMarkup(createElement(FirstSteps, { state, view, onSetup: () => {}, onCoach: () => {}, onSample: () => {} })), "", `${view} hides the starter guide after a completed workout`);
  }
});
